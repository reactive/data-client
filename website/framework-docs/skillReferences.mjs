/**
 * Generates agent skill references (.agents/skills/<skill>/references/*.md)
 * from the docs, so skills stay in sync with the site without shipping MDX.
 *
 * Each skill lists the docs it needs in `references.json`:
 *
 *   { "frameworks": ["react", "vue"], "docs": { "useSuspense.md": "docs/core/api/useSuspense.md" } }
 *
 * The first framework with the page writes `<name>.md`; later ones write
 * `<name>.<framework>.md` only when their page differs.
 *
 * Renders are cached in node_modules/.cache, keyed by the files each one read,
 * so a run only parses docs that changed (and skips loading remark entirely
 * when none did).
 *
 * Usage: node website/framework-docs/skillReferences.mjs [--check]
 */
import crypto from 'node:crypto';
import fs from 'node:fs';
import { createRequire } from 'node:module';
import path from 'node:path';

import { ROOT, SITE, rel } from './site.mjs';

const { walk, frontMatter } = createRequire(import.meta.url)('./index.js');
const SKILLS = path.join(ROOT, '.agents/skills');
const MANIFEST = 'references.json';
const HEADER = '<!-- Generated by `yarn build:skills` from';
const MD = /\.mdx?$/;

/** Content ignoring the header and which framework's docs links point to */
const comparable = content =>
  content?.replace(/^.*\n/, '').replaceAll(`${SITE}/vue/`, `${SITE}/docs/`);

const hash = value => crypto.createHash('sha1').update(value).digest('hex');
const hashes = new Map();
/** Content hash of a repo file, or '' if it doesn't exist */
function fileHash(file) {
  if (!hashes.has(file)) {
    const abs = path.join(ROOT, file);
    hashes.set(file, fs.existsSync(abs) ? hash(fs.readFileSync(abs)) : '');
  }
  return hashes.get(file);
}

/**
 * Invalidates the whole cache: the generator and its dependencies, plus every
 * doc's path and front matter (doc ids, routes and which pages Vue has).
 */
function globalKey() {
  const generator = 'website/framework-docs';
  const parts = [
    ...fs
      .readdirSync(path.join(ROOT, generator))
      .filter(f => /\.m?js$/.test(f))
      .map(f => `${generator}/${f}`),
    'yarn.lock',
  ]
    .sort()
    .map(fileHash);
  const docs = path.join(ROOT, 'docs');
  for (const file of walk(docs)
    // skip generated mirrors like docs/.core-vue
    .filter(f => MD.test(f) && !f.startsWith('.'))
    .sort())
    parts.push(
      file,
      frontMatter(fs.readFileSync(path.join(docs, file), 'utf8')),
    );
  return hash(parts.join('\0'));
}

const CACHE_FILE = path.join(ROOT, 'node_modules/.cache/skill-references.json');
const key = globalKey();
let cache;
try {
  cache = JSON.parse(fs.readFileSync(CACHE_FILE, 'utf8'));
} catch {
  // first run
}
if (cache?.key !== key) cache = { key, routes: {}, renders: {} };
/** Whether this run added to the cache, so it needs saving */
let missed = false;

let renderer;
/** docsToMarkdown.mjs loads remark and scans the docs, so only on a cache miss */
const load = async () => (renderer ??= await import('./docsToMarkdown.mjs'));

/**
 * Route of each skill doc -> its reference name, so links between them stay
 * local; `key` identifies the set for render cache keys
 */
async function localRoutesFor(docs, framework) {
  const key = hash(`${framework}\0${JSON.stringify(docs)}`);
  if (!cache.routes[key]) {
    const { routeOf } = await load();
    cache.routes[key] = Object.entries(docs)
      .filter(([, doc]) => !path.basename(doc).startsWith('_'))
      .map(([name, doc]) => [routeOf(path.join(ROOT, doc), framework), name]);
    missed = true;
  }
  return { key, routes: new Map(cache.routes[key]) };
}

/** docToMarkdown(), reused from the cache while the files it read are unchanged */
async function render(doc, framework, { key, routes: localRoutes }) {
  const cacheKey = `${doc}\0${framework}\0${key}`;
  const hit = cache.renders[cacheKey];
  if (hit && Object.entries(hit.deps).every(([f, h]) => fileHash(f) === h))
    return hit.body;
  const { docToMarkdown, trackDeps } = await load();
  const resolveRoute = url => {
    const [, route, hash = ''] = url.match(/^([^#]*)(#.*)?$/);
    return localRoutes.has(route) ?
        `./${localRoutes.get(route)}${hash}`
      : SITE + url;
  };
  const { value: body, deps } = trackDeps(() =>
    docToMarkdown(path.join(ROOT, doc), framework, { resolveRoute }),
  );
  cache.renders[cacheKey] = {
    deps: Object.fromEntries(deps.map(f => [f, fileHash(f)])),
    body,
  };
  missed = true;
  return body;
}

/** Map of reference path -> content for one skill */
async function generateSkill(skillDir) {
  const { frameworks, docs } = JSON.parse(
    fs.readFileSync(path.join(skillDir, MANIFEST), 'utf8'),
  );
  const out = new Map();
  for (const doc of Object.values(docs)) {
    // generated references aren't sources: they may not be regenerated yet
    if (!doc.startsWith('docs/'))
      throw new Error(`${rel(skillDir)}/${MANIFEST}: ${doc} is not in docs/`);
    if (!fs.existsSync(path.join(ROOT, doc)))
      throw new Error(`${rel(skillDir)}/${MANIFEST}: ${doc} does not exist`);
  }
  for (const framework of frameworks) {
    const localRoutes = await localRoutesFor(docs, framework);
    for (const [name, doc] of Object.entries(docs)) {
      const body = await render(doc, framework, localRoutes);
      if (!body) continue;
      const content = `${HEADER} ${doc} (${framework}). Edit the source doc, not this file. -->\n\n${body}`;
      const primary = path.join(skillDir, 'references', name);
      // the first framework that has the page writes `<name>.md`
      if (!out.has(primary)) out.set(primary, content);
      else if (comparable(out.get(primary)) !== comparable(content))
        out.set(primary.replace(MD, `.${framework}.md`), content);
    }
  }
  return out;
}

/** Generated files currently on disk, by path */
function generatedFiles(dir) {
  if (!fs.existsSync(dir)) return new Map();
  return new Map(
    fs
      .readdirSync(dir)
      .filter(f => f.endsWith('.md'))
      .map(f => path.join(dir, f))
      .filter(f => !fs.lstatSync(f).isSymbolicLink())
      .map(f => [f, fs.readFileSync(f, 'utf8')])
      .filter(([, content]) => content.startsWith(HEADER)),
  );
}

/** [file, content] for every file to write, with content null to delete */
const changes = [];
for (const skill of fs.readdirSync(SKILLS).sort()) {
  const skillDir = path.join(SKILLS, skill);
  if (!fs.existsSync(path.join(skillDir, MANIFEST))) continue;
  const out = await generateSkill(skillDir);
  const current = generatedFiles(path.join(skillDir, 'references'));
  for (const file of current.keys())
    if (!out.has(file)) changes.push([file, null]);
  for (const [file, content] of out)
    if (current.get(file) !== content) changes.push([file, content]);
}

if (missed) {
  try {
    fs.mkdirSync(path.dirname(CACHE_FILE), { recursive: true });
    fs.writeFileSync(CACHE_FILE, JSON.stringify(cache));
  } catch {
    // no cache dir (e.g. read-only checkout); next run renders everything
  }
}

if (process.argv.includes('--check')) {
  if (changes.length) {
    console.error(
      `Skill references are out of date with the docs:\n  ${changes.map(([f]) => rel(f)).join('\n  ')}\nRun \`yarn build:skills\` and commit the result.`,
    );
    process.exit(1);
  }
  console.log('Skill references are up to date.');
} else {
  for (const [file, content] of changes) {
    // also replaces a symlink left from before references were generated
    fs.rmSync(file, { force: true });
    if (content === null) continue;
    fs.mkdirSync(path.dirname(file), { recursive: true });
    fs.writeFileSync(file, content);
  }
  console.log(`Updated ${changes.length} skill reference files.`);
}

const problems = fs.readdirSync(SKILLS).flatMap(skill => {
  const skillMd = path.join(SKILLS, skill, 'SKILL.md');
  const refs = path.join(SKILLS, skill, 'references');
  const text = fs.existsSync(skillMd) ? fs.readFileSync(skillMd, 'utf8') : '';
  const files = fs.existsSync(refs) ? fs.readdirSync(refs) : [];
  const manifest = path.join(SKILLS, skill, MANIFEST);
  const { frameworks = [] } =
    fs.existsSync(manifest) ?
      JSON.parse(fs.readFileSync(manifest, 'utf8'))
    : {};
  return [
    // links to references that no longer exist (renamed or removed docs)
    ...[...text.matchAll(/\]\((references\/[^)#\s]+)/g)]
      .map(([, link]) => link)
      .filter(link => !fs.existsSync(path.join(SKILLS, skill, link)))
      .map(link => `${rel(skillMd)} links to missing ${link}`),
    // symlinked docs ship raw MDX; list them in references.json instead
    ...files
      .filter(
        f => MD.test(f) && fs.lstatSync(path.join(refs, f)).isSymbolicLink(),
      )
      .map(f => `${rel(refs)}/${f} is a symlink; add it to ${MANIFEST}`),
    // agents only find framework variants if SKILL.md tells them to look
    ...frameworks
      .slice(1)
      .filter(fw => files.some(f => f.endsWith(`.${fw}.md`)))
      .filter(fw => !text.includes(`.${fw}.md`))
      .map(
        fw =>
          `${rel(skillMd)} needs a note to read \`<name>.${fw}.md\` instead of \`<name>.md\` for ${fw} projects`,
      ),
  ];
});
if (problems.length) {
  console.error(`Skill problems:\n  ${[...new Set(problems)].join('\n  ')}`);
  process.exit(1);
}
